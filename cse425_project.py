    def __init__(self, csv_path):
        self.samples = []
        with open(csv_path, 'r', encoding='utf-8') as f:
            reader = csv.DictReader(f)
            for row in reader:
                self.samples.append((row['audio_path'], row['text_path'], row['genre']))

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        # Load audio
        audio = np.load(self.samples[idx][0]).flatten()
        if len(audio) > FIXED_AUDIO_SIZE:
            audio = audio[:FIXED_AUDIO_SIZE]
        else:
            audio = np.pad(audio, (0, FIXED_AUDIO_SIZE - len(audio)))
        audio_min, audio_max = audio.min(), audio.max()
        if audio_max - audio_min > 0:
            audio = (audio - audio_min) / (audio_max - audio_min)
        else:
            audio = np.zeros_like(audio)

        # Load text
        text = np.load(self.samples[idx][1])
        text_min, text_max = text.min(), text.max()
        if text_max - text_min > 0:
            text = (text - text_min) / (text_max - text_min)
        else:
            text = np.zeros_like(text)

        # Combine features
        hybrid_feature = np.concatenate([audio, text])
        return torch.FloatTensor(hybrid_feature), self.samples[idx][2]

